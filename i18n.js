const FR_FORMATS = {
  added: (name, n) => `${name} ajouté au panier (${n} article${n > 1 ? 's' : ''})`,
  boxAdded: (size, n) => `Votre boîte de ${size} ajoutée au panier (${n} article${n > 1 ? 's' : ''})`,
  chosen: (n, size) => `${n} sur ${size} choisis`,
  interested: what => `Je m’intéresse à : ${what}.`,
};
const EN_FORMATS = {
  added: (name, n) => `${name} added to bag (${n} item${n > 1 ? 's' : ''})`,
  boxAdded: (size, n) => `Your box of ${size} added to bag (${n} item${n > 1 ? 's' : ''})`,
  chosen: (n, size) => `${n} of ${size} chosen`,
  interested: what => `I'm interested in ${what}.`,
};

const EN = Object.fromEntries(Object.entries(FR).map(([en, fr]) => [fr, en]));
let lang = 'en';

const norm = s => s.replace(/\s+/g, ' ').trim();

// prices: "$4.99" <-> "4,99 $"
function price(n) {
  const v = Number(n);
  const fixed = Number.isInteger(v) ? String(v) : v.toFixed(2);
  return lang === 'fr' ? `${fixed.replace('.', ',')} $` : `$${fixed}`;
}

// translate one string into the current language, whichever language it is in now
function tr(text) {
  const en = EN[text] ?? text;
  let m = en.match(/^\$(\d+(?:\.\d\d)?)$/) || text.match(/^(\d+(?:,\d\d)?) \$$/);
  if (m) return price(m[1].replace(',', '.'));
  return lang === 'fr' ? (FR[en] ?? en) : en;
}

const SKIP = 'script, style, [data-no-i18n]';
const ATTRS = ['alt', 'aria-label', 'placeholder', 'data-label'];

// original English for each text node / attribute, captured the first time we see it
const origText = new WeakMap();
const origAttr = new WeakMap();
let origTitle, origDesc;
const toLang = en => {
  const m = en.match(/^\$(\d+(?:\.\d\d)?)$/);
  if (m) return price(m[1]);
  return lang === 'fr' ? (FR[en] ?? en) : en;
};

function translatePage() {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
    acceptNode: n => n.parentElement && !n.parentElement.closest(SKIP) ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT,
  });
  for (let n = walker.nextNode(); n; n = walker.nextNode()) {
    const m = n.nodeValue.match(/^(\s*)([\s\S]*?)(\s*)$/);
    if (!m[2]) continue;
    const cur = norm(m[2]);
    // text written later by script.js is already in the current language
    if (!origText.has(n)) origText.set(n, EN[cur] ?? cur);
    const out = toLang(origText.get(n));
    if (out !== cur) n.nodeValue = m[1] + out + m[3];
  }
  ATTRS.forEach(a => document.querySelectorAll(`[${a}]`).forEach(el => {
    if (el.closest(SKIP) || !el.getAttribute(a).trim()) return;
    if (!origAttr.has(el)) origAttr.set(el, {});
    const store = origAttr.get(el);
    if (!(a in store)) { const v = norm(el.getAttribute(a)); store[a] = EN[v] ?? v; }
    el.setAttribute(a, toLang(store[a]));
  }));
  const desc = document.querySelector('meta[name="description"]');
  origTitle ??= norm(document.title);
  origDesc ??= norm(desc.content);
  document.title = toLang(origTitle);
  desc.content = toLang(origDesc);
  document.documentElement.lang = lang === 'fr' ? 'fr-CA' : 'en';
}

window.i18n = {
  get lang() { return lang; },
  t: tr,
  price,
  f: (key, ...args) => (lang === 'fr' ? FR_FORMATS : EN_FORMATS)[key](...args),
  set(next) {
    lang = next === 'fr' ? 'fr' : 'en';
    translatePage();
    try { localStorage.setItem('lang', lang); } catch (e) {}
    document.querySelectorAll('.lang button').forEach(b => b.setAttribute('aria-pressed', b.dataset.lang === lang));
    document.dispatchEvent(new CustomEvent('langchange', { detail: lang }));
  },
};

